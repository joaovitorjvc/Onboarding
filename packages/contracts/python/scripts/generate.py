"""Gera o modelo Pydantic do Formato_de_Erro a partir do schema canônico."""

from __future__ import annotations

import argparse
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT.parent / "schemas" / "error-format.schema.json"
GENERATED = ROOT / "nuagehub_contracts" / "generated" / "error_format.py"


def generate(output: Path = GENERATED) -> None:
    """Gera um arquivo Python com modelos Pydantic v2."""
    output.parent.mkdir(parents=True, exist_ok=True)
    executable = shutil.which("datamodel-codegen")
    if executable is None:
        raise RuntimeError("datamodel-codegen não está disponível no ambiente uv.")
    subprocess.run(  # noqa: S603
        [
            executable,
            "--input",
            str(SCHEMA),
            "--input-file-type",
            "jsonschema",
            "--output",
            str(output),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--extra-fields",
            "forbid",
            "--disable-timestamp",
            "--use-annotated",
        ],
        check=True,
    )
    generated_content = output.read_text(encoding="utf-8")
    output.write_text(
        generated_content.replace(
            "# generated by datamodel-codegen:",
            "# gerado por datamodel-codegen:",
        ).replace("#   filename:", "#   arquivo:"),
        encoding="utf-8",
    )


def main() -> None:
    """Executa o gerador pela linha de comando."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=GENERATED)
    args = parser.parse_args()
    generate(args.output)


if __name__ == "__main__":
    main()
